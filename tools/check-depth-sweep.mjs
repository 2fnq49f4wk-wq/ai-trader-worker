// [V33.204] 깊이 스윕 계약 게이트
//   실측(2026-08-22): 10층 4,580,070 파라미터 모델의 valAcc 가 49.3% 로, 워커 폴백 2층(53.3%)보다
//   낮았다. 신뢰 게이트가 외부 모델을 거부하고 워커가 자가학습으로 내려갔고, 그마저 하한 47.8% 로
//   MIND 하한 52.5% 에 못 미쳐 DNN 은 위원회 투표에서 통째로 빠져 있었다(wDnn=0).
//   깊이를 ★재서★ 정하기로 했다. 그러면 그 비교가 공정해야 한다 — 이 게이트가 그 조건을 지킨다.
import fs from "node:fs";
const src = fs.readFileSync("trainer/modal/modal_train.py", "utf8");
let bad = 0;
const ok = (m) => console.log("  ok   " + m);
const no = (m) => { console.error("  FAIL " + m); bad++; };

// ── ① 같은 자로 잰다 — 선택 기준이 워커 승격 게이트와 같은 통계인가 ──────────
//   워커는 '유효표본 Wilson 하한(accLB)' 으로 승격을 판정한다. 스윕이 valAcc 로 고르면
//   "여기선 이겼는데 저기선 떨어지는" 모델을 고르게 된다 — 두 자가 다르면 비교가 무의미하다.
if (!/rank\.sort\(key=lambda r: \(-r\["lb"\]/.test(src))
  no("깊이스윕: 승자를 하한(lb)으로 고르지 않는다 — 워커 게이트와 다른 자로 재면 안 된다");
else ok("승자 선택 기준 = 유효표본 Wilson 하한(워커 승격 게이트와 동일한 자)");

// 동률일 때 큰 모델이 자동으로 이기면 안 된다(파라미터 오름차순이 마지막 키).
if (!/-r\["acc"\], r\["params"\]\)/.test(src))
  no("깊이스윕: 동률 처리에 파라미터 수가 없다 — 근거 없이 큰 모델이 이길 수 있다");
else ok("동률 처리 — valAcc → 파라미터 적은 쪽(근거 없으면 작은 모델)");

// ── ② 같은 조건에서 잰다 ────────────────────────────────────────────────
//   후보마다 표본·분할·시드가 다르면 그 비교는 깊이가 아니라 운을 재는 것이다.
//   Xtr/Xva 는 fit_arch 밖에서 한 번 만들어지고, 시드는 one_seed(1000 + sd*7) 로 고정이다.
{
  const iFit = src.indexOf("def fit_arch(");
  const iSplit = src.indexOf("Xtr = torch.tensor(");
  if (iFit < 0) no("깊이스윕: fit_arch 가 없다");
  else if (iSplit < 0) no("깊이스윕: 학습/검증 분할을 찾을 수 없다");
  else if (iSplit > iFit)
    no("깊이스윕: 분할이 fit_arch 안에서 만들어진다 — 후보마다 다른 데이터를 보게 된다");
  else ok("표본·분할은 fit_arch 밖에서 1회 — 후보 전원이 같은 데이터를 본다");
  const fitBody = src.slice(iFit, iFit + 9000);
  if (!/one_seed\(1000 \+ sd \* 7\)/.test(fitBody))
    no("깊이스윕: 시드가 고정되어 있지 않다 — 깊이가 아니라 운을 재게 된다");
  else ok("시드 고정(1000 + sd×7) — 후보 전원이 같은 시드 계열로 학습된다");
}

// ── ③ 정기 실행 비용을 늘리지 않는다 ────────────────────────────────────
//   Modal 무료 크레딧이 $30/월이고 현재 사용이 ~$21/월이다. 6시간마다 후보를 셋씩 학습하면
//   예산을 넘긴다 — 스윕은 사람이 부를 때만 돌아야 한다.
if (!/depth_sweep: bool = False/.test(src))
  no("깊이스윕: 기본값이 꺼져 있지 않다 — 정기 실행 비용이 늘어난다(크레딧 $30/월 한도)");
else ok("기본 꺼짐 — 정기 6시간 실행의 비용은 그대로");
if (!/if depth_sweep:/.test(src)) no("깊이스윕: 분기 자체가 없다");

// ── ④ 순위가 실행 로그에만 남고 사라지지 않는가 ──────────────────────────
//   이 저장소가 반복해 겪은 실패다(V33.199: 판단은 났는데 밖으로 나올 길이 없었다).
if (!/"depthSweep": sweep_note/.test(src))
  no("깊이스윕: 순위를 결과값에 싣지 않는다 — 실행 로그가 사라지면 근거도 사라진다");
else ok("순위를 결과값(depthSweep)에 싣는다 — 나중에 왜 그 깊이인지 확인할 수 있다");
if (!/1·2위 하한 차이가 0\.5%p 미만/.test(src))
  no("깊이스윕: 1·2위 차이가 미미할 때 경고하지 않는다 — 잡음으로 깊이를 바꾸게 된다");
else ok("1·2위 하한 차이가 0.5%p 미만이면 경고(다음 스윕에서 뒤집힐 수 있다고 명시)");

// ── ⑤ 승자를 전체 시드로 다시 학습해 내보내는가 ─────────────────────────
//   순위는 적은 시드로 매기고(싸다), 내보내는 모델은 전체 시드여야 한다. 순위용 모델을
//   그대로 올리면 앙상블이 얇아져 하한이 낮아지고, 그러면 승격 게이트를 또 못 넘는다.
{
  const i = src.indexOf("if depth_sweep:");
  const seg = src.slice(i, i + 3000);
  if (!/K = _K_full/.test(seg))
    no("깊이스윕: 승자 재학습 전에 시드 수를 원래대로 되돌리지 않는다 — 얇은 앙상블이 업로드된다");
  else if (!/_fin = fit_arch\(dims, win\["tag"\]/.test(seg))
    no("깊이스윕: 승자를 전체 시드로 다시 학습하지 않는다");
  else ok("승자만 전체 시드로 재학습해 내보낸다(순위는 적은 시드로 — 크레딧 절약)");
}

if (bad) { console.error(`\n깊이 스윕 계약 위반 ${bad}건 — 배포 차단`); process.exit(1); }
console.log("  ok   깊이 스윕 계약 통과 — 같은 자·같은 조건으로 재고, 근거를 남긴다");
